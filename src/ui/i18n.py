LANGS = ("zh", "en")


class Translator:
    def __init__(self, lang="zh"):
        self.lang = lang if lang in LANGS else LANGS[0]

    def set(self, lang):
        self.lang = lang if lang in LANGS else LANGS[0]
        return self.lang

    def t(self, key, args=None):
        template = STRINGS[self.lang].get(key)
        if template is None:
            return key
        if not args:
            return template
        try:
            return template.format(**args)
        except (KeyError, IndexError, ValueError):
            return template
